import pandas as pd
import joblib
import streamlit as st
import plotly.express as px
import plotly.graph_objects as go

st.set_page_config(page_title='Telco Customer Churn Prediction', page_icon=":clapper:", layout='wide')

'''
This is the basic app for predicting Churn possibilities on loaded dataset
'''

@st.cache_resource
def load_artifacts():
    model = joblib.load('churn_model.pkl')
    scaler= joblib.load('scaler.pkl')
    feature= joblib.load('feature_names.pkl')
    return model, scaler, feature

model, scaler, feature = load_artifacts()

st.title('Telco Customer Churn Prediction Dashboard using Machine Learning')

st.sidebar.header('Customer information')

gender=st.sidebar.selectbox('Gender', ['Male', 'Female'])
senior_citizen=st.sidebar.selectbox('Senior Citizen', ['NO', 'Yes'])
partner=st.sidebar.selectbox('Partner', ['NO', 'Yes'])
dependents=st.sidebar.selectbox('Dependents', ['NO', 'Yes'])
tenure=st.sidebar.slider('Tenure', 0, 72, 12)
monthly_charges=st.sidebar.number_input('Monthly Charges', 0.0, 200.0, 70.0)
total_charges=st.sidebar.number_input('Total Charges', 0.0, 10000.0, 1000.0)

def FEATURE_ENGINEERING():
    row={c:0 for c in feature}
    for k,v in {
      'tenure':tenure,
      'monthly_charges':monthly_charges,
      'total_charges':total_charges,
    }.items():
        if k in row:
          row[k]=v
    return pd.DataFrame([row], columns= feature)


if st.button('Predict'):
  X=FEATURE_ENGINEERING()
  Xs=scaler.transform(X)
  pred=model.predict(Xs)[0]
  proba=model.predict_proba(Xs)[0]
  churn_prob = proba[1]

  st.subheader("Prediction Confidence")

  st.progress(float(churn_prob))

  st.write(f"### {churn_prob*100:.2f}% chance of Churn")
  if pred==1:
    st.error('Likely to Churn')
  else:
    st.success('Likely to Stay')

  st.metric('Churn Probability', f'{proba[1]*100:.2f}%')
  st.metric('Non-Churn Probability', f'{proba[0]*100:.2f}%')

if st.button("🔄 Reset"):
    st.rerun()

st.markdown("---")

st.header("Prediction Dashboard")

fig = px.pie(
    values=[proba[1], proba[0]],
    names=["Churn", "Stay"],
    hole=0.5,
    title="Churn vs Non-Churn Probability",
)

st.plotly_chart(fig, use_container_width=True)
# Example list from bulk prediction
all_probabilities = [0.82, 0.15, 0.48, 0.67, 0.91]

hist = px.histogram(
    x=all_probabilities,
    nbins=10,
    title="Distribution of Churn Probabilities",
    labels={"x": "Probability", "y": "Customers"},
)

st.plotly_chart(hist, use_container_width=True)



