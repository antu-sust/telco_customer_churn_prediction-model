@st.cache_resource
def load_artifects():
  model = joblib.load('churn_model.pkl')
  scaler= joblib.load('scaler.pkl')
  features= joblib.load('feature_names.pkl')
  return model, scaler, features

model, scaler, features = load_artifects()

